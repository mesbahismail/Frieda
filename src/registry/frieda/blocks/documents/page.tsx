type SortKey = "added" | "name" | "size" | "modified" | "shared"
type Sort = { key: SortKey; dir: "asc" | "desc" }

const sortPresets: { label: string; sort: Sort }[] = [
  { label: "Latest", sort: { key: "added", dir: "desc" } },
  { label: "Oldest", sort: { key: "added", dir: "asc" } },
  { label: "Name A–Z", sort: { key: "name", dir: "asc" } },
  { label: "Name Z–A", sort: { key: "name", dir: "desc" } },
  { label: "Largest", sort: { key: "size", dir: "desc" } },
]

const accepted = ".pdf,.png,.jpg,.jpeg,.webp,.csv,.doc,.docx,.xls,.xlsx,.txt"
const MAX_MB = 10

function personName(id: string) {
  return personById(id)?.name ?? (id === support.id ? support.name : id)
}

function compare(a: DocumentItem, b: DocumentItem, { key, dir }: Sort) {
  const sign = dir === "asc" ? 1 : -1
  switch (key) {
    case "name":
      return sign * a.name.localeCompare(b.name, undefined, { numeric: true })
    case "size":
      return sign * (a.size - b.size)
    case "shared":
      return sign * (a.sharedWith.length - b.sharedWith.length)
    default:
      // Sorting is stable, so documents added the same day keep their order.
      return sign * (new Date(a[key]).getTime() - new Date(b[key]).getTime())
  }
}

function downloadDocument(doc: DocumentItem) {
  if (doc.url) {
    const a = document.createElement("a")
    a.href = doc.url
    a.download = doc.name
    a.click()
  } else {
    const blob = makePdf(doc.name, [
      "Frieda Inc - 21023 Pearson Point Road, Gateway Avenue",
      "",
      `Document: ${doc.name}`,
      `Added: ${shortDate(doc.added)}    Last modified: ${shortDate(doc.modified)}`,
      `Shared with: ${doc.sharedWith.map(personName).join(", ")}`,
      "",
      "This is a sample document generated by the Frieda template.",
    ])
    downloadBlob(blob, `${doc.name.replace(/\s+/g, "-").toLowerCase()}.pdf`)
  }
  toast.success(`Downloading ${doc.name}`)
}

