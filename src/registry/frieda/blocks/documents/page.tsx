function HeaderCell({
  label,
  sortKey,
  sort,
  onSort,
  className,
}: {
  label: string
  sortKey?: SortKey
  sort: Sort
  onSort: (key: SortKey) => void
  className?: string
}) {
  const active = sortKey && sort.key === sortKey
  return (
    <th scope="col" className={cn("px-4 text-left font-medium first:pl-4", className)} aria-sort={active ? (sort.dir === "asc" ? "ascending" : "descending") : undefined}>
      {sortKey ? (
        <button type="button" onClick={() => onSort(sortKey)} className={cn("flex items-center gap-1.5 whitespace-nowrap transition-colors hover:text-white", active && "text-white")}>
          {label}
          <ChevronDown className={cn("size-3.5 transition-transform", active && sort.dir === "asc" && "rotate-180")} />
        </button>
      ) : (
        <span className="flex items-center gap-1.5">
          {label} <ChevronDown className="size-3.5" />
        </span>
      )}
    </th>
  )
}

