function pageList(current: number, total: number): (number | "…")[] {
  if (total <= 7) return Array.from({ length: total }, (_, i) => i + 1)
  const pages = new Set([1, 2, 3, total - 2, total - 1, total, current - 1, current, current + 1])
  const sorted = [...pages].filter((p) => p >= 1 && p <= total).sort((a, b) => a - b)
  return sorted.flatMap((p, i) => (i && p - sorted[i - 1] > 1 ? ["…" as const, p] : [p]))
}

function Pagination({ page, pages, onChange }: { page: number; pages: number; onChange: (page: number) => void }) {
  if (pages <= 1) return null
  const btn = "grid size-[30px] place-items-center rounded-[8px] text-[14px] tabular-nums transition-colors"
  return (
    <nav aria-label="Pagination" className="mt-6 flex items-center justify-center gap-2">
      <button type="button" aria-label="Previous page" disabled={page === 1} onClick={() => onChange(page - 1)} className={cn(btn, "text-[#d6d6d6] hover:bg-white/5 disabled:opacity-30")}>
        <ChevronLeft className="size-4" />
      </button>
      {pageList(page, pages).map((p, i) =>
        p === "…" ? (
          <span key={`gap-${i}`} className="w-[30px] text-center text-[#a3a3a3]">
            …
          </span>
        ) : (
          <button
            key={p}
            type="button"
            aria-current={p === page ? "page" : undefined}
            onClick={() => onChange(p)}
            className={cn(btn, p === page ? "bg-teal text-[#123]" : "text-[#d6d6d6] hover:bg-white/5")}
          >
            {p}
          </button>
        )
      )}
      <button type="button" aria-label="Next page" disabled={page === pages} onClick={() => onChange(page + 1)} className={cn(btn, "text-[#d6d6d6] hover:bg-white/5 disabled:opacity-30")}>
        <ChevronRight className="size-4" />
      </button>
    </nav>
  )
}

function RenameDialog({ doc, onClose }: { doc: DocumentItem | null; onClose: () => void }) {
  const [name, setName] = React.useState("")
  const [prev, setPrev] = React.useState<DocumentItem | null>(null)
  if (doc !== prev) {
    setPrev(doc)
    if (doc) setName(doc.name)
  }
  return (
    <FriedaDialog open={!!doc} onOpenChange={(o) => !o && onClose()} title="Rename document">
      <form
        className="mt-5 space-y-5"
        onSubmit={(e) => {
          e.preventDefault()
          if (!doc || !name.trim()) return
          actions.updateDocument(doc.id, { name: name.trim(), modified: new Date().toISOString() })
          toast.success("Document renamed")
          onClose()
        }}
      >
        <input autoFocus value={name} onChange={(e) => setName(e.target.value)} aria-label="Document name" className={fieldClass} onFocus={(e) => e.target.select()} />
        <button type="submit" disabled={!name.trim()} className={cn(primaryAction, "h-12 w-full")}>
          Save
        </button>
      </form>
    </FriedaDialog>
  )
}

function ShareDialog({ doc, onClose }: { doc: DocumentItem | null; onClose: () => void }) {
  const live = useFrieda((s) => s.documents.find((d) => d.id === doc?.id))
  const shared = live?.sharedWith ?? []
  const toggle = (id: string) => {
    if (!live) return
    actions.updateDocument(live.id, {
      sharedWith: shared.includes(id) ? shared.filter((s) => s !== id) : [...shared, id],
    })
  }
  return (
    <FriedaDialog open={!!doc} onOpenChange={(o) => !o && onClose()} title="Share document" description={doc?.name} className="sm:max-w-[480px]">
      <div className="frieda-scroll -mx-2 mt-5 max-h-[320px] overflow-y-auto px-2">
        {[support.id, ...people.map((p) => p.id)].map((id) => {
          const on = shared.includes(id)
          return (
            <button
              key={id}
              type="button"
              onClick={() => toggle(id)}
              aria-pressed={on}
              className="flex w-full items-center gap-3 rounded-xl px-2 py-2 text-left text-[15px] transition-colors hover:bg-white/[0.04]"
            >
              <PersonAvatar id={id} name={personName(id)} tone={id === support.id ? "purple" : "teal"} className="size-9" />
              <span className="flex-1">{personName(id)}</span>
              <span className={cn("grid size-6 place-items-center rounded-full border transition-colors", on ? "border-teal bg-teal text-[#123]" : "border-white/20")}>
                {on && <Check className="size-3.5" />}
              </span>
            </button>
          )
        })}
      </div>
      <div className="mt-5 flex gap-3">
        <button
          type="button"
          className={cn(outlineAction, "flex-1")}
          onClick={() => {
            navigator.clipboard?.writeText(`${window.location.origin}/documents?doc=${doc?.id}`).catch(() => {})
            toast.success("Link copied to clipboard")
          }}
        >
          Copy link
        </button>
        <button type="button" className={cn(primaryAction, "flex-1")} onClick={onClose}>
          Done
        </button>
      </div>
    </FriedaDialog>
  )
}

