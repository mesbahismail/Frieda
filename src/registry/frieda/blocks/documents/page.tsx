function DocumentsView() {
  const router = useRouter()
  const params = useSearchParams()
  const filter = params.get("q")?.trim() ?? ""
  const all = useFrieda((s) => s.documents)
  const documents = filter ? all.filter((d) => d.name.toLowerCase().includes(filter.toLowerCase())) : all
  const [view, setView] = React.useState<"grid" | "list">("grid")
  const [sort, setSort] = React.useState<Sort>(sortPresets[0].sort)
  const [page, setPage] = React.useState(1)
  const [dragging, setDragging] = React.useState(false)
  const [opened, setOpened] = React.useState<DocumentItem | null>(null)
  const [renaming, setRenaming] = React.useState<DocumentItem | null>(null)
  const [sharing, setSharing] = React.useState<DocumentItem | null>(null)
  const [deleting, setDeleting] = React.useState<DocumentItem | null>(null)
  const input = React.useRef<HTMLInputElement>(null)

  const perPage = view === "grid" ? 9 : 10
  const sorted = [...documents].sort((a, b) => compare(a, b, sort))
  const pages = Math.max(1, Math.ceil(sorted.length / perPage))
  const current = Math.min(page, pages)
  const items = sorted.slice((current - 1) * perPage, current * perPage)
  const preset = sortPresets.find((p) => p.sort.key === sort.key && p.sort.dir === sort.dir)

  const handlers: Handlers = { onOpen: setOpened, onRename: setRenaming, onShare: setSharing, onDelete: setDeleting }

  function upload(files: FileList | null) {
    if (!files?.length) return
    let added = 0
    for (const file of Array.from(files)) {
      const mb = file.size / 1024 / 1024
      if (mb > MAX_MB) {
        toast.error(`${file.name} is larger than ${MAX_MB} MB`)
        continue
      }
      const now = new Date().toISOString()
      actions.addDocument({
        id: `d-${Date.now()}-${added}`,
        name: file.name,
        kind: "file",
        size: Math.max(0.1, Math.round(mb * 10) / 10),
        added: now,
        modified: now,
        sharedWith: [],
        url: URL.createObjectURL(file),
        mime: file.type,
      })
      added++
    }
    if (added) {
      setSort(sortPresets[0].sort)
      setPage(1)
      toast.success(added === 1 ? "Document uploaded" : `${added} documents uploaded`)
    }
    if (input.current) input.current.value = ""
  }

  return (
    <div
      onDragOver={(e) => {
        if (!e.dataTransfer.types.includes("Files")) return
        e.preventDefault()
        setDragging(true)
      }}
      onDragLeave={(e) => {
        if (e.currentTarget.contains(e.relatedTarget as Node)) return
        setDragging(false)
      }}
      onDrop={(e) => {
        e.preventDefault()
        setDragging(false)
        upload(e.dataTransfer.files)
      }}
      className="relative"
    >
      <PageHeader
        title="Documents"
        actions={
          <>
            <div role="group" aria-label="View" className="flex h-[38px] items-center rounded-[10px] border border-[#4a4a4a] p-[3px]">
              {(
                [
                  ["list", List, "List view"],
                  ["grid", LayoutGrid, "Grid view"],
                ] as const
              ).map(([id, Icon, label], i) => (
                <React.Fragment key={id}>
                  {i > 0 && <span className="mx-px h-5 w-px bg-[#4a4a4a]" />}
                  <button
                    type="button"
                    aria-label={label}
                    aria-pressed={view === id}
                    onClick={() => {
                      setView(id)
                      setPage(1)
                    }}
                    className={cn("grid h-full w-[38px] place-items-center rounded-[7px] text-[#9c9c9c] transition-colors hover:text-white", view === id && "bg-white/[0.07] text-white")}
                  >
                    <Icon className="size-[18px]" strokeWidth={1.7} />
                  </button>
                </React.Fragment>
              ))}
            </div>
            <DropdownMenu>
              <DropdownMenuTrigger className={outlineAction}>
                <ArrowDownUp /> {preset?.label ?? "Custom"} <ChevronDown className="!size-4" />
              </DropdownMenuTrigger>
              <DropdownMenuContent align="end" className="w-44">
                {sortPresets.map((p) => (
                  <DropdownMenuItem key={p.label} onSelect={() => setSort(p.sort)} className="justify-between">
                    {p.label}
                    {preset === p && <Check className="text-teal" />}
                  </DropdownMenuItem>
                ))}
              </DropdownMenuContent>
            </DropdownMenu>
            <button type="button" className={primaryAction} onClick={() => input.current?.click()}>
              <Upload /> Upload new
            </button>
            <input ref={input} type="file" multiple accept={accepted} className="hidden" onChange={(e) => upload(e.target.files)} />
          </>
        }
      />

      {filter && (
        <div className="-mt-1 mb-5 flex items-center gap-2 text-[14px] text-subtle">
          Showing {documents.length} result{documents.length === 1 ? "" : "s"} for
          <button
            type="button"
            onClick={() => router.replace("/documents", { scroll: false })}
            className="inline-flex h-7 items-center gap-1.5 rounded-full bg-teal/10 px-3 text-teal transition-colors hover:bg-teal/20"
          >
            “{filter}” <X className="size-3.5" />
            <span className="sr-only">Clear search</span>
          </button>
        </div>
      )}

      {documents.length === 0 ? (
        <div className="frieda-card grid place-items-center py-24 text-center">
          <div>
            <p className="text-subtle">{filter ? "No documents match this search." : "No documents yet. Drop files here or upload one."}</p>
            <button type="button" className={cn(primaryAction, "mt-4")} onClick={() => input.current?.click()}>
              <Upload /> Upload new
            </button>
          </div>
        </div>
      ) : view === "grid" ? (
        <>
          <GridView items={items} {...handlers} />
          <Pagination page={current} pages={pages} onChange={setPage} />
        </>
      ) : (
        <section className="frieda-card p-[10px] pb-6">
          <ListView items={items} sort={sort} onSort={(key) => setSort((s) => ({ key, dir: s.key === key && s.dir === "desc" ? "asc" : "desc" }))} {...handlers} />
          <Pagination page={current} pages={pages} onChange={setPage} />
        </section>
      )}

      {dragging && (
        <div className="pointer-events-none absolute inset-0 top-[86px] z-20 grid place-items-center rounded-[18px] border-2 border-dashed border-teal bg-[#1d1d1d]/85 backdrop-blur-sm">
          <div className="text-center">
            <Upload className="mx-auto size-8 text-teal" />
            <p className="mt-3 text-[16px]">Drop files to upload</p>
            <p className="mt-1 text-[13px] text-subtle">PDF, images, CSV or Office files up to {MAX_MB} MB</p>
          </div>
        </div>
      )}

      <PreviewDialog doc={opened} onClose={() => setOpened(null)} />
      <RenameDialog doc={renaming} onClose={() => setRenaming(null)} />
      <ShareDialog doc={sharing} onClose={() => setSharing(null)} />
      <ConfirmDialog
        open={!!deleting}
        onOpenChange={(o) => !o && setDeleting(null)}
        title="Delete document?"
        description={deleting ? `${deleting.name} will be removed for you and everyone it’s shared with.` : undefined}
        onConfirm={() => {
          if (!deleting) return
          actions.removeDocument(deleting.id)
          toast.success(`${deleting.name} deleted`)
        }}
      />
    </div>
  )
}

export default function DocumentsPage() {
  return (
    <React.Suspense>
      <DocumentsView />
    </React.Suspense>
  )
}
